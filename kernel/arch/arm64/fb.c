void fb_char(uint32_t x, uint32_t y, char c, uint32_t rgb)
{
    if (!ready) return;
    const uint8_t *g;
    static const uint8_t box[8] = {0xFF,0x81,0x81,0x81,0x81,0x81,0xFF,0};
    if (c < 32 || c > 126) g = box;
    else g = font8[(int)c - 32];
    for (uint32_t row = 0; row < 8; row++)
        for (uint32_t col = 0; col < 8; col++)
            if (g[row] & (0x80 >> col)) fb_pixel(x + col, y + row, rgb);
}

void fb_text(uint32_t x, uint32_t y, const char *s, uint32_t rgb)
{
    for (; *s; s++, x += 8) fb_char(x, y, *s, rgb);
}

