#include "fb.h"
#include "mailbox.h"
#include "uart.h"
#include "mmu.h"

static volatile uint32_t *fb;
static uint32_t fb_w, fb_h, fb_pitch_px;
static int ready;
/* The firmware's "pixel order" says which component sits at the lowest address. Callers
 * here pass 0xRRGGBB, which a little-endian store puts down blue-first -- so that matches
 * the BGR setting, and the RGB setting is the one needing the swap. */
static int swap_rb;

int fb_init(uint32_t width, uint32_t height)
{
    uint64_t addr = 0;
    uint32_t pitch = 0, size = 0, order = 1;
    if (mailbox_framebuffer(width, height, &addr, &pitch, &size, &order) != 0 || addr == 0) {
        uart_puts("fb: the firmware refused a framebuffer\n");
        return -1;
    }
    /* The GPU scans this memory out; pixels held back in the CPU's cache would never show. */
    if (mmu_enabled()) mmu_set_uncached(addr, size ? size : (uint64_t)pitch * height);
    fb = (volatile uint32_t *)addr;
    fb_w = width;
    fb_h = height;
    fb_pitch_px = pitch / 4;          /* the firmware reports bytes per row */
    if (fb_pitch_px == 0) fb_pitch_px = width;
    swap_rb = (order == 1);
    ready = 1;
    return 0;
}

int fb_ready(void) { return ready; }
uint32_t fb_width(void) { return fb_w; }
uint32_t fb_height(void) { return fb_h; }

void fb_pixel(uint32_t x, uint32_t y, uint32_t rgb)
{
    if (!ready || x >= fb_w || y >= fb_h) return;
    if (swap_rb) rgb = (rgb & 0x00FF00) | ((rgb & 0xFF) << 16) | ((rgb >> 16) & 0xFF);
    fb[y * fb_pitch_px + x] = rgb;
}

void fb_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t rgb)
{
    if (!ready) return;
    for (uint32_t j = 0; j < h; j++)
        for (uint32_t i = 0; i < w; i++)
            fb_pixel(x + i, y + j, rgb);
}

void fb_clear(uint32_t rgb) { fb_rect(0, 0, fb_w, fb_h, rgb); }

